"""Golden playthroughs (PLAN testing strategy item 4). Three fixed seeds.

Each test regenerates the playthrough with ``generate_playthrough.playthrough`` (fully random
action policy driven by ``seed``, which also samples chance outcomes) and diffs it against
tests/playthroughs/<name>.txt. Golden files are generated by the implementer; any diff must be
explained in the commit message. A missing golden is a failure.
"""

import difflib
from pathlib import Path

import pytest
from open_spiel.python.algorithms import generate_playthrough

GOLDEN = Path(__file__).resolve().parent / "playthroughs"

CASES = [
    ("king_is_dead_2p_seed1", 2, 1),
    ("king_is_dead_3p_seed2", 3, 2),
    ("king_is_dead_2p_seed3", 2, 3),
]


@pytest.mark.parametrize(("name", "players", "seed"), CASES, ids=[c[0] for c in CASES])
def test_golden_playthrough(name: str, players: int, seed: int) -> None:
    import kingisdead.game  # noqa: F401  (registers the game)

    path = GOLDEN / f"{name}.txt"
    game = f"python_king_is_dead(players={players})"
    assert path.exists(), (
        f"golden playthrough {path} is missing; generate it with "
        f"generate_playthrough.playthrough('{game}', [], seed={seed})"
    )
    actual = generate_playthrough.playthrough(game, [], seed=seed)
    expected = path.read_text()
    if actual != expected:
        diff = "\n".join(
            list(
                difflib.unified_diff(
                    expected.splitlines(), actual.splitlines(), "golden", "actual", lineterm="", n=2
                )
            )[:60]
        )
        pytest.fail(f"playthrough {name} differs from golden file:\n{diff}")


def test_playthrough_is_deterministic() -> None:
    """Same seed twice gives identical text (guards against hidden nondeterminism)."""
    import kingisdead.game  # noqa: F401

    g = "python_king_is_dead(players=2)"
    a = generate_playthrough.playthrough(g, [], seed=1)
    b = generate_playthrough.playthrough(g, [], seed=1)
    assert a == b
